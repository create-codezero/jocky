#[cfg(target_os = "linux")]
pub mod linux {
    use super::*;

    /// Linux implementation of the safe platform abstraction.
    #[derive(Debug, Default, Clone, Copy)]
    pub struct LinuxPlatform;

    impl LinuxPlatform {
        pub fn new() -> Self {
            Self
        }
    }

    impl PlatformOps for LinuxPlatform {
        fn system_information(
            &self,
        ) -> Result<SystemInformation, PlatformError> {
            Ok(SystemInformation {
                operating_system: "linux".to_string(),
                architecture: current_architecture().to_string(),
                hostname: hostname(),
                process_id: current_process_id(),
            })
        }

        fn collect_processes(
            &self,
        ) -> Result<CollectionResult, PlatformError> {
            let mut result = CollectionResult::empty("processes");

            let proc_dir = std::path::Path::new("/proc");

            if !proc_dir.exists() {
                return Err(PlatformError::Unsupported(
                    "/proc is unavailable",
                ));
            }

            for entry in std::fs::read_dir(proc_dir)? {
                let entry = match entry {
                    Ok(value) => value,
                    Err(err) => {
                        result.warnings.push(err.to_string());
                        continue;
                    }
                };

                let file_name = entry.file_name();

                let pid_text = file_name.to_string_lossy();

                if !pid_text.chars().all(|c| c.is_ascii_digit()) {
                    continue;
                }

                let pid = pid_text.clone();

                let status_path =
                    entry.path().join("status");

                let mut observation =
                    Observation::new("processes")
                        .with_field("pid", pid.to_string());

                match std::fs::read_to_string(&status_path) {
                    Ok(status) => {
                        for line in status.lines() {
                            if let Some(name) =
                                line.strip_prefix("Name:")
                            {
                                observation = observation
                                    .with_field(
                                        "name",
                                        name.trim(),
                                    );
                            }

                            if let Some(state) =
                                line.strip_prefix("State:")
                            {
                                observation = observation
                                    .with_field(
                                        "state",
                                        state.trim(),
                                    );
                            }

                            if let Some(uid) =
                                line.strip_prefix("Uid:")
                            {
                                observation = observation
                                    .with_field(
                                        "uid",
                                        uid.trim(),
                                    );
                            }
                        }
                    }

                    Err(err) => {
                        result.warnings.push(format!(
                            "cannot read {}: {}",
                            status_path.display(),
                            err
                        ));
                    }
                }

                result.observations.push(observation);
            }

            Ok(result)
        }

        fn collect_network_connections(
            &self,
        ) -> Result<CollectionResult, PlatformError> {
            let mut result =
                CollectionResult::empty("network_connections");

            collect_proc_network_file(
                "/proc/net/tcp",
                "tcp",
                &mut result,
            )?;

            collect_proc_network_file(
                "/proc/net/udp",
                "udp",
                &mut result,
            )?;

            collect_proc_network_file(
                "/proc/net/tcp6",
                "tcp6",
                &mut result,
            )?;

            collect_proc_network_file(
                "/proc/net/udp6",
                "udp6",
                &mut result,
            )?;

            Ok(result)
        }

        fn collect_users(
            &self,
        ) -> Result<CollectionResult, PlatformError> {
            let mut result = CollectionResult::empty("users");

            let passwd = std::fs::read_to_string("/etc/passwd")?;

            for line in passwd.lines() {
                if line.trim().is_empty()
                    || line.starts_with('#')
                {
                    continue;
                }

                let fields: Vec<&str> =
                    line.split(':').collect();

                if fields.len() < 7 {
                    continue;
                }

                let observation =
                    Observation::new("users")
                        .with_field("username", fields[0])
                        .with_field("uid", fields[2])
                        .with_field("gid", fields[3])
                        .with_field("home", fields[5])
                        .with_field("shell", fields[6]);

                result.observations.push(observation);
            }

            Ok(result)
        }

        fn collect_services(
            &self,
        ) -> Result<CollectionResult, PlatformError> {
            let mut result = CollectionResult::empty("services");

            //
            // Read-only systemd inspection.
            //
            // We deliberately do not enable/disable/start/stop services.
            //
            let systemd_path =
                std::path::Path::new("/etc/systemd/system");

            if systemd_path.exists() {
                for entry in std::fs::read_dir(systemd_path)? {
                    let entry = match entry {
                        Ok(value) => value,
                        Err(err) => {
                            result.warnings.push(err.to_string());
                            continue;
                        }
                    };

                    let path = entry.path();

                    if path.is_file() {
                        let name = path
                            .file_name()
                            .map(|x| x.to_string_lossy().to_string())
                            .unwrap_or_default();

                        result.observations.push(
                            Observation::new("services")
                                .with_field("name", name)
                                .with_field(
                                    "path",
                                    path.display().to_string(),
                                ),
                        );
                    }
                }
            } else {
                result.warnings.push(
                    "/etc/systemd/system is unavailable"
                        .to_string(),
                );
            }

            Ok(result)
        }

        fn collect_startup_items(
            &self,
        ) -> Result<CollectionResult, PlatformError> {
            let mut result =
                CollectionResult::empty("startup_items");

            let locations = [
                "/etc/rc.local",
                "/etc/profile",
                "/etc/profile.d",
            ];

            for location in locations {
                let path =
                    std::path::Path::new(location);

                if !path.exists() {
                    continue;
                }

                let observation =
                    Observation::new("startup_items")
                        .with_field(
                            "path",
                            path.display().to_string(),
                        )
                        .with_field(
                            "type",
                            if path.is_dir() {
                                "directory"
                            } else {
                                "file"
                            },
                        );

                result.observations.push(observation);
            }

            Ok(result)
        }

        fn collect_file_metadata(
            &self,
            path: &str,
        ) -> Result<CollectionResult, PlatformError> {
            collect_standard_file_metadata(path)
        }
    }
}


// ----------------------------------------------------------------------
// Generic file metadata collector
// ----------------------------------------------------------------------

/// Collect metadata without reading/executing the file contents.
///
/// This is useful for a JOCKY IR operation such as:
///
///     collect file_metadata
///
/// when the agent has received an explicitly authorized path.
pub fn collect_standard_file_metadata(
    path: &str,
) -> Result<CollectionResult, PlatformError> {
    use std::path::Path;

    let target = Path::new(path);

    let metadata = std::fs::symlink_metadata(target)
        .map_err(|err| {
            if err.kind() == std::io::ErrorKind::PermissionDenied {
                PlatformError::PermissionDenied(
                    path.to_string(),
                )
            } else {
                PlatformError::Io(err)
            }
        })?;

    let file_type = metadata.file_type();

    let mut observation =
        Observation::new("file_metadata")
            .with_field(
                "path",
                target.display().to_string(),
            )
            .with_field(
                "is_file",
                file_type.is_file().to_string(),
            )
            .with_field(
                "is_directory",
                file_type.is_dir().to_string(),
            )
            .with_field(
                "is_symlink",
                file_type.is_symlink().to_string(),
            )
            .with_field(
                "size",
                metadata.len().to_string(),
            );

    if let Ok(created) = metadata.created() {
        if let Ok(duration) =
            created.duration_since(UNIX_EPOCH)
        {
            observation = observation.with_field(
                "created_unix_ms",
                duration.as_millis().to_string(),
            );
        }
    }

    if let Ok(modified) = metadata.modified() {
        if let Ok(duration) =
            modified.duration_since(UNIX_EPOCH)
        {
            observation = observation.with_field(
                "modified_unix_ms",
                duration.as_millis().to_string(),
            );
        }
    }

    Ok(CollectionResult {
        artifact: "file_metadata".to_string(),
        observations: vec![observation],
        warnings: Vec::new(),
    })
}


