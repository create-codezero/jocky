#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn timestamp_is_nonzero() {
        assert!(current_time_ms() > 0);
    }

    #[test]
    fn platform_is_known() {
        let platform = current_platform();

        assert!(
            platform == "windows"
                || platform == "linux"
                || platform == "macos"
                || platform == "unknown"
        );
    }

    #[test]
    fn architecture_is_nonempty() {
        assert!(!current_architecture().is_empty());
    }

    #[test]
    fn observation_fields_work() {
        let item = Observation::new("test")
            .with_field("name", "jocky")
            .with_field("version", "0.3");

        assert_eq!(
            item.fields.get("name"),
            Some(&"jocky".to_string())
        );

        assert_eq!(
            item.fields.get("version"),
            Some(&"0.3".to_string())
        );
    }

    #[test]
    fn unsupported_artifact_returns_error() {
        let agent = platform();

        let result = agent.collect("does_not_exist");

        assert!(result.is_err());
    }

    #[test]
    fn system_information_is_available() {
        let agent = platform();

        let result = agent.system_information();

        assert!(result.is_ok());

        let info = result.unwrap();

        assert!(!info.operating_system.is_empty());
        assert!(!info.architecture.is_empty());
    }
}