// Linux /proc helpers
// ----------------------------------------------------------------------

#[cfg(target_os = "linux")]
fn collect_proc_network_file(
    path: &str,
    protocol: &str,
    result: &mut CollectionResult,
) -> Result<(), PlatformError> {
    let content = match std::fs::read_to_string(path) {
        Ok(value) => value,
        Err(err) => {
            result.warnings.push(format!(
                "cannot read {}: {}",
                path, err
            ));

            return Ok(());
        }
    };

    for line in content.lines().skip(1) {
        let fields: Vec<&str> =
            line.split_whitespace().collect();

        if fields.len() < 4 {
            continue;
        }

        let local_address = fields[1];
        let remote_address = fields[2];
        let state = fields[3];

        let observation =
            Observation::new("network_connections")
                .with_field("protocol", protocol)
                .with_field(
                    "local_address",
                    local_address,
                )
                .with_field(
                    "remote_address",
                    remote_address,
                )
                .with_field("state", state);

        result.observations.push(observation);
    }

    Ok(())
}


