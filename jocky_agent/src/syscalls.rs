//! JOCKY Platform Abstraction Layer
//!
//! This module deliberately provides a safe, read-only interface for
//! forensic collection. It does not perform:
//!   - direct system-call invocation
//!   - API-hook bypassing
//!   - API unhooking
//!   - process hollowing
//!   - thread hijacking
//!   - DLL injection
//!   - privilege escalation
//!   - persistence
//!   - security-product tampering
//!
//! The purpose of this layer is to keep the JOCKY execution engine
//! independent from platform-specific collection mechanisms.
//
//! Architecture:
//
//!     JOCKY IR
//!        |
//!        v
//!   Agent Dispatcher
//!        |
//!        v
//!   PlatformOps
//!      /     \
//! Windows   Linux
//!
//! Both platforms expose the same forensic abstraction.

use std::collections::BTreeMap;
use std::fmt;
use std::time::{SystemTime, UNIX_EPOCH};

/// Errors generated by the platform abstraction layer.
#[derive(Debug)]
pub enum PlatformError {
    Unsupported(&'static str),
    PermissionDenied(String),
    Io(std::io::Error),
    Parse(String),
    InvalidRequest(String),
}

impl fmt::Display for PlatformError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Unsupported(msg) => write!(f, "unsupported operation: {msg}"),
            Self::PermissionDenied(msg) => write!(f, "permission denied: {msg}"),
            Self::Io(err) => write!(f, "I/O error: {err}"),
            Self::Parse(msg) => write!(f, "parse error: {msg}"),
            Self::InvalidRequest(msg) => write!(f, "invalid request: {msg}"),
        }
    }
}

impl std::error::Error for PlatformError {}

impl From<std::io::Error> for PlatformError {
    fn from(value: std::io::Error) -> Self {
        Self::Io(value)
    }
}

/// A single forensic observation.
///
/// Keeping the result structured rather than returning arbitrary strings
/// makes the output suitable for the JOCKY evidence ledger.
#[derive(Debug, Clone)]
pub struct Observation {
    pub artifact: String,
    pub timestamp_unix_ms: u128,
    pub fields: BTreeMap<String, String>,
}

impl Observation {
    pub fn new<S: Into<String>>(artifact: S) -> Self {
        Self {
            artifact: artifact.into(),
            timestamp_unix_ms: current_time_ms(),
            fields: BTreeMap::new(),
        }
    }

    pub fn with_field<K, V>(mut self, key: K, value: V) -> Self
    where
        K: Into<String>,
        V: Into<String>,
    {
        self.fields.insert(key.into(), value.into());
        self
    }
}

/// Result returned by a collector.
///
/// `observations` contains normalized forensic records.
/// `warnings` contains non-fatal collection problems.
#[derive(Debug, Clone)]
pub struct CollectionResult {
    pub artifact: String,
    pub observations: Vec<Observation>,
    pub warnings: Vec<String>,
}

impl CollectionResult {
    pub fn empty<S: Into<String>>(artifact: S) -> Self {
        Self {
            artifact: artifact.into(),
            observations: Vec::new(),
            warnings: Vec::new(),
        }
    }
}

/// Normalized platform information.
#[derive(Debug, Clone)]
pub struct SystemInformation {
    pub operating_system: String,
    pub architecture: String,
    pub hostname: String,
    pub process_id: u32,
}

/// The platform-neutral forensic interface.
///
/// `main.rs` and the IR executor should depend on this trait rather than
/// knowing whether the agent is running on Windows or Linux.
pub trait PlatformOps {
    /// Return basic host information.
    fn system_information(&self) -> Result<SystemInformation, PlatformError>;

    /// Collect running-process metadata.
    ///
    /// This is metadata collection only; no process is opened for code
    /// injection, modification, suspension, or execution.
    fn collect_processes(&self) -> Result<CollectionResult, PlatformError>;

    /// Collect network-connection metadata.
    fn collect_network_connections(&self) -> Result<CollectionResult, PlatformError>;

    /// Collect logged-in users where supported.
    fn collect_users(&self) -> Result<CollectionResult, PlatformError>;

    /// Collect service metadata where supported.
    fn collect_services(&self) -> Result<CollectionResult, PlatformError>;

    /// Collect startup-item metadata where supported.
    fn collect_startup_items(&self) -> Result<CollectionResult, PlatformError>;

    /// Collect file metadata for an explicitly supplied path.
    ///
    /// This function intentionally does not execute or modify the target.
    fn collect_file_metadata(
        &self,
        path: &str,
    ) -> Result<CollectionResult, PlatformError>;

    /// Dispatch a normalized JOCKY artifact name.
    fn collect(&self, artifact: &str) -> Result<CollectionResult, PlatformError> {
        match artifact {
            "processes" => self.collect_processes(),

            "network_connections" => {
                self.collect_network_connections()
            }

            "users" => self.collect_users(),

            "services" => self.collect_services(),

            "startup_items" => self.collect_startup_items(),

            "system_information" => {
                let info = self.system_information()?;

                let observation = Observation::new("system_information")
                    .with_field("operating_system", info.operating_system)
                    .with_field("architecture", info.architecture)
                    .with_field("hostname", info.hostname)
                    .with_field("process_id", info.process_id.to_string());

                Ok(CollectionResult {
                    artifact: "system_information".to_string(),
                    observations: vec![observation],
                    warnings: Vec::new(),
                })
            }

            "file_metadata" => Err(PlatformError::InvalidRequest(
                "file_metadata requires an explicit path; \
                 use collect_file_metadata()"
                    .to_string(),
            )),

            "authentication_events" => {
                Err(PlatformError::Unsupported(
                    "authentication_events is not implemented \
                     by the generic platform layer",
                ))
            }

            other => Err(PlatformError::InvalidRequest(format!(
                "unknown JOCKY artifact: {other}"
            ))),
        }
    }
}

/// Return the current Unix timestamp in milliseconds.
pub fn current_time_ms() -> u128 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis()
}

/// Return the current process ID.
pub fn current_process_id() -> u32 {
    std::process::id()
}

/// Return a normalized platform identifier.
///
/// These values correspond to the platform names used by the JOCKY IR.
pub fn current_platform() -> &'static str {
    if cfg!(target_os = "windows") {
        "windows"
    } else if cfg!(target_os = "linux") {
        "linux"
    } else if cfg!(target_os = "macos") {
        "macos"
    } else {
        "unknown"
    }
}

/// Return the target architecture.
pub fn current_architecture() -> &'static str {
    std::env::consts::ARCH
}

/// Return the current hostname.
///
/// Failure is converted into a stable fallback rather than terminating
/// the complete forensic collection pipeline.
pub fn hostname() -> String {
    std::env::var("COMPUTERNAME")
        .or_else(|_| std::env::var("HOSTNAME"))
        .unwrap_or_else(|_| "unknown".to_string())
}

// ----------------------------------------------------------------------
// Windows implementation
// ----------------------------------------------------------------------

#[cfg(target_os = "windows")]
pub mod windows {
    use super::*;
    use std::process::Command;
    use sysinfo::System;

    #[derive(Debug, Default, Clone)]
    pub struct WindowsPlatform;

    impl WindowsPlatform {
        pub fn new() -> Self {
            Self
        }
    }

    impl PlatformOps for WindowsPlatform {
        fn system_information(&self) -> Result<SystemInformation, PlatformError> {
            Ok(SystemInformation {
                operating_system: "windows".to_string(),
                architecture: current_architecture().to_string(),
                hostname: hostname(),
                process_id: current_process_id(),
            })
        }

        fn collect_processes(&self) -> Result<CollectionResult, PlatformError> {
            let mut result = CollectionResult::empty("processes");
            let mut sys = System::new_all();
            sys.refresh_processes();

            for (pid, process) in sys.processes() {
                let exe_path = process.exe()
                    .map(|p| p.to_string_lossy().to_string())
                    .unwrap_or_else(|| "unknown".to_string());

                let obs = Observation::new("processes")
                    .with_field("pid", pid.as_u32().to_string())
                    .with_field("name", process.name().to_string()) // FIXED: removed to_string_lossy()
                    .with_field("exe_path", exe_path)
                    .with_field("memory_kb", (process.memory() / 1024).to_string());
                
                result.observations.push(obs);
            }
            Ok(result)
        }

        fn collect_network_connections(&self) -> Result<CollectionResult, PlatformError> {
            let mut result = CollectionResult::empty("network_connections");

            // Living-off-the-Land: Use native netstat to avoid hooking network APIs
            if let Ok(output) = Command::new("netstat").args(&["-ano"]).output() {
                let stdout = String::from_utf8_lossy(&output.stdout);

                for line in stdout.lines().skip(4) {
                    let parts: Vec<&str> = line.split_whitespace().collect();
                    if parts.len() >= 4 {
                        let protocol = parts[0];
                        let local_address = parts[1];
                        let remote_address = parts[2];
                        
                        let state = if parts.len() == 5 { parts[3] } else { "LISTENING" };
                        let pid = if parts.len() == 5 { parts[4] } else { parts[3] };

                        let obs = Observation::new("network_connections")
                            .with_field("protocol", protocol.to_string())
                            .with_field("local_address", local_address.to_string())
                            .with_field("remote_address", remote_address.to_string())
                            .with_field("state", state.to_string())
                            .with_field("pid", pid.to_string());
                        
                        result.observations.push(obs);
                    }
                }
            } else {
                result.warnings.push("Failed to execute netstat utility".to_string());
            }
            Ok(result)
        }

        fn collect_users(&self) -> Result<CollectionResult, PlatformError> {
            let mut result = CollectionResult::empty("users");

            if let Ok(output) = Command::new("net").arg("user").output() {
                let stdout = String::from_utf8_lossy(&output.stdout);
                for line in stdout.lines() {
                    if line.starts_with("---") || line.contains("User accounts") || line.contains("command completed") {
                        continue;
                    }
                    for username in line.split_whitespace() {
                        let obs = Observation::new("users")
                            .with_field("username", username.to_string())
                            .with_field("enabled", "true".to_string());
                        result.observations.push(obs);
                    }
                }
            }
            Ok(result)
        }

        fn collect_services(&self) -> Result<CollectionResult, PlatformError> {
            let mut result = CollectionResult::empty("services");

            if let Ok(output) = Command::new("sc").arg("query").output() {
                let stdout = String::from_utf8_lossy(&output.stdout);
                let mut current_name = String::new();

                for line in stdout.lines() {
                    let trimmed = line.trim();
                    if trimmed.starts_with("SERVICE_NAME:") {
                        current_name = trimmed.replace("SERVICE_NAME:", "").trim().to_string();
                    }
                    if trimmed.starts_with("STATE") {
                        let obs = Observation::new("services")
                            .with_field("name", current_name.clone())
                            .with_field("status", trimmed.to_string());
                        result.observations.push(obs);
                    }
                }
            }
            Ok(result)
        }

        fn collect_startup_items(&self) -> Result<CollectionResult, PlatformError> {
            let mut result = CollectionResult::empty("startup_items");
            // Standard simulated registry pull for SIH prototype
            result.observations.push(Observation::new("startup_items")
                .with_field("name", "HKLM Run".to_string())
                .with_field("path", r"HKLM\Software\Microsoft\Windows\CurrentVersion\Run".to_string()));
            Ok(result)
        }

        fn collect_file_metadata(&self, path: &str) -> Result<CollectionResult, PlatformError> {
            collect_standard_file_metadata(path)
        }
    }
}

